"""
Bayesian Electromagnetic Field Estimation from D-LinOSS States
==============================================================

This script integrates the Bayesian estimation framework proposed by
Koide-Majima et al. (2024) into our D-LinOSS visual category investigation.

The problem:
Instead of just matching learned category templates to raw BOLD readouts,
we know D-LinOSS has ALREADY learned the temporal BOLD contrast activation
as internal electromagnetic oscillator states (the x(t) variables).

The goal:
We deduce the *original field activation* (where the cause of the BOLD
effect came from spatially) by solving the inverse problem using
Stochastic Gradient Langevin Dynamics (SGLD).

Bayesian Formulation:
    p(z | x_target) ∝ p(x_target | z) * p(z)

    - z: The underlying spatial electromagnetic field driving the voxels.
    - x_target: The observed D-LinOSS oscillator states for a given category.
    - p(x_target | z): The visual likelihood. Driven by the similarity
      between the target oscillator states and the states generated by
      feeding z through the model's learned encoding (B matrix).
    - p(z): The prior. We use our ResonanceNetwork or a regularized
      spatial prior (smoothness/sparsity) to keep z biologically plausible.

We use SGLD to sample from this posterior because it is intractable to
solve analytically. We can then project the estimated field `z` back to
the 3D brain space to see exactly WHICH voxels/regions are driving the
category perception.
"""

