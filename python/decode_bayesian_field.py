def preprocess_run(run_ts, TR):
    """Lightweight preprocessing: detrend + normalize."""
    N, T = run_ts.shape
    cleaned = run_ts.copy().astype(np.float32)
    t_axis = np.arange(T, dtype=np.float32)
    for i in range(N):
        coeffs = np.polyfit(t_axis, cleaned[i], 1)
        cleaned[i] -= np.polyval(coeffs, t_axis)
    mu = cleaned.mean(axis=1, keepdims=True)
    sigma = cleaned.std(axis=1, keepdims=True)
    sigma = np.where(sigma < 1e-8, 1.0, sigma)
    cleaned = (cleaned - mu) / sigma
    return np.clip(cleaned, -5.0, 5.0).T  # (T, N)


def extract_target_oscillator_states(model, x_input):
    """
    Run the D-LinOSS model and extract the internal oscillator states x(t)
    for a given input. We use the FIRST block's states as our primary target
    since it's closest to the physical voxel mapping.
    """
    model.eval()
    with torch.no_grad():
        h = model.encoder(x_input)
        block = model.blocks[0]  # Just use the first block for direct spatial mapping
        h_normed = block.norm(h)
        
        ssm = block.ssm
        L, H = h_normed.shape
        P = ssm.state_dim
        
        B_complex = torch.view_as_complex(ssm.B.contiguous())
        A, G, dt = ssm._soft_project(ssm.A_diag, ssm.G_diag, ssm.dt_raw)
        
        Bu = h_normed.to(B_complex.dtype) @ B_complex.T  # (L, P)
        
        S = 1.0 + dt * G
        M11 = 1.0 / S
        M12 = -dt * A / S
        M21 = dt / S
        M22 = 1.0 - dt.pow(2) * A / S
        
        M = torch.cat([M11, M12, M21, M22])
        M_elements = M.unsqueeze(0).repeat(L, 1)
        
        F1 = (dt / S).unsqueeze(0) * Bu
        F2 = (dt.pow(2) / S).unsqueeze(0) * Bu
        F_cat = torch.cat([F1, F2], dim=-1)
        
        _, xs_re = parallel_scan(M_elements, F_cat.real)
        _, xs_im = parallel_scan(M_elements, F_cat.imag)
        
        ys_re = xs_re[:, P:]
        ys_im = xs_im[:, P:]
        osc_states = torch.complex(ys_re, ys_im)
        
    return osc_states  # (L, P) complex


# ============================================================================
#  Bayesian Estimation via SGLD
# ============================================================================

def simulate_oscillator_states(model, z):
    """
    Simulate the oscillator states generated by a candidate field pattern `z`.
    z is shape (N_voxels,), so we treat it as a constant static activation
    over a small time window L=10 to let the oscillators react.
    """
    L = 10
    z_seq = z.unsqueeze(0).expand(L, -1)  # (L, N_voxels)
    
    h = model.encoder(z_seq)
    block = model.blocks[0]
    h_normed = block.norm(h)
    
    ssm = block.ssm
    P = ssm.state_dim
    
    B_complex = torch.view_as_complex(ssm.B.contiguous())
    A, G, dt = ssm._soft_project(ssm.A_diag, ssm.G_diag, ssm.dt_raw)
    
    Bu = h_normed.to(B_complex.dtype) @ B_complex.T
    
    S = 1.0 + dt * G
    M11 = 1.0 / S
    M12 = -dt * A / S
    M21 = dt / S
    M22 = 1.0 - dt.pow(2) * A / S
    
    M = torch.cat([M11, M12, M21, M22])
    M_elements = M.unsqueeze(0).repeat(L, 1)
    
    F1 = (dt / S).unsqueeze(0) * Bu
    F2 = (dt.pow(2) / S).unsqueeze(0) * Bu
    F_cat = torch.cat([F1, F2], dim=-1)
    
    _, xs_re = parallel_scan(M_elements, F_cat.real)
    _, xs_im = parallel_scan(M_elements, F_cat.imag)
    
    ys_re = xs_re[:, P:]
    ys_im = xs_im[:, P:]
    osc_states = torch.complex(ys_re, ys_im)
    
    # Return the average steady-state magnitude
    return torch.abs(osc_states).mean(dim=0)  # (P,)


def sgld_field_estimation(model, target_magnitudes, num_voxels, 
                          iterations=500, a=0.00015, b=0.15, gamma=0.055, T=1e-7):
    """
    Run Stochastic Gradient Langevin Dynamics (SGLD) to find the source
    electromagnetic field 'z' that caused the observed BOLD contrast.
    
    Based on Koide-Majima et al. (2024) Bayesian framework:
    z_{t+1} = z_t + (eps_t / 2) * grad(log_posterior) + noise
    """
    # Initialize the candidate field 'z' as random noise
    # We want to find the spatial cause, so z represents voxel activations
    z = torch.randn(num_voxels, requires_grad=True, dtype=torch.float32)
    
    # We want to track the best z found
    best_loss = float('inf')
    best_z = None
    
    target_mag = torch.tensor(target_magnitudes, dtype=torch.float32)
    
    for t in range(iterations):
        if z.grad is not None:
            z.grad.zero_()
            
        # 1. Forward model: What oscillator states does this field z cause?
        simulated_mag = simulate_oscillator_states(model, z)
        
        # 2. Likelihood (Visual/Field): Similarity between simulated and target
        # We use Pearson correlation as proposed by the paper, implemented as Cosine Similarity
        # on mean-centered data.
        sim_mean = simulated_mag.mean()
        tgt_mean = target_mag.mean()
        sim_c = simulated_mag - sim_mean
        tgt_c = target_mag - tgt_mean
        
        # Adding a small epsilon to denominator to prevent division by zero
        cov = torch.sum(sim_c * tgt_c)
        var_sim = torch.sqrt(torch.sum(sim_c**2) + 1e-8)
        var_tgt = torch.sqrt(torch.sum(tgt_c**2) + 1e-8)
        correlation = cov / (var_sim * var_tgt)
        
        # The paper formulation: log p(phi_hat | I) = (1/T) * Similarity
        log_likelihood = (1.0 / T) * correlation
        
        # 3. Prior p(z): We assume fields are sparse and spatially coherent.
        # We add L1 sparsity and L2 magnitude penalties.
        log_prior = -0.1 * torch.sum(torch.abs(z)) - 0.01 * torch.sum(z**2)
        
        # 4. Posterior
        log_posterior = log_likelihood + log_prior
        
        # We want to maximize posterior, so loss is -log_posterior
        loss = -log_posterior
        loss.backward()
        
        with torch.no_grad():
            # SGLD Step size schedule
            eps_t = a / ((b + t)**gamma)
            
            # Gradient step
            z += (eps_t / 2.0) * z.grad
            
            # Langevin noise injection
            noise = torch.randn_like(z) * np.sqrt(eps_t)
            z += noise
            
            # Keep track of best result
            current_loss = loss.item()
            if current_loss < best_loss:
                best_loss = current_loss
                best_z = z.clone().detach()

        if (t+1) % 100 == 0:
            print(f"      SGLD Iter {t+1:3d}: correlation = {correlation.item():.4f}, "
                  f"prior = {log_prior.item():.2f}")
            
    return best_z.numpy()


