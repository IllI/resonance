def run_bayesian_investigation(subject_dir, subject_name, max_voxels=500):
    """
    Train D-LinOSS, extract the electromagnetic signatures of visual categories,
    and deduce the spatial sources of those signatures using Bayesian estimation.
    """
    print(f"\n{'='*70}")
    print(f"  BAYESIAN FIELD ESTIMATION: {subject_name}")
    print(f"  Deducing spatial cause of BOLD contrast from learned dynamics")
    print(f"{'='*70}")

    # 1. Load data
    bold_runs, events_runs, TR = load_haxby_subject(subject_dir, max_runs=12)
    n_runs = len(bold_runs)
    
    # 2. Select category-sensitive voxels using between-group ANOVA
    print(f"\n  [Phase 1] Extracting brain data & selecting top {max_voxels} voxels...")
    bold_concat = np.concatenate(bold_runs, axis=-1)
    ts_2d, brain_mask, coords = extract_brain_voxels(bold_concat, percentile=20)
    
    labels_per_run = []
    categories = set()
    for events, bold in zip(events_runs, bold_runs):
        run_labels = build_block_labels(events, bold.shape[-1], TR)
        labels_per_run.append(run_labels)
        categories.update(l for l in run_labels if l != 'rest')
    categories = sorted(categories)
    all_labels_flat = [l for rl in labels_per_run for l in rl]
    
    # ANOVA F-stat
    cat_means = {}
    cat_counts = {}
    for cat in categories:
        idx = [i for i, l in enumerate(all_labels_flat) if l == cat]
        if idx:
            cat_means[cat] = ts_2d[:, idx].mean(axis=1)
            cat_counts[cat] = len(idx)
            
    grand_mean = ts_2d.mean(axis=1)
    ss_between = np.zeros(ts_2d.shape[0])
    ss_within = np.zeros(ts_2d.shape[0])
    
    for cat in categories:
        if cat in cat_means:
            ss_between += cat_counts[cat] * (cat_means[cat] - grand_mean)**2
            idx = [i for i, l in enumerate(all_labels_flat) if l == cat]
            if idx:
                ss_within += np.sum((ts_2d[:, idx] - cat_means[cat][:, None])**2, axis=1)

    k = len(cat_means)
    n_total = sum(cat_counts.values())
    f_stat = (ss_between / max(k-1, 1)) / (ss_within / max(n_total-k, 1) + 1e-10)

    top_idx = np.argsort(f_stat)[-max_voxels:]
    selected_coords = coords[top_idx]
    
    # 3. Preprocess per run
    print(f"  [Phase 2] Preprocessing and training D-LinOSS (Self-Supervised)...")
    clean_runs = []
    for bold in bold_runs:
        run_selected = bold[brain_mask][top_idx]
        cleaned = preprocess_run(run_selected, TR)
        clean_runs.append(cleaned)
        
    concat_clean = np.concatenate(clean_runs, axis=0)
    
    # 4. Train D-LinOSS model
    model = DLinOSSModel(
        input_dim=max_voxels, state_dim=32, hidden_dim=64,
        output_dim=max_voxels, num_blocks=3, drop_rate=0.0
    )
    
    x_all = torch.tensor(concat_clean, dtype=torch.float32)
    model.train()
    optimizer = torch.optim.Adam(model.parameters(), lr=1e-3)
    
    for epoch in range(100):
        optimizer.zero_grad()
        y = model(x_all)
        loss = torch.nn.functional.mse_loss(y, x_all)
        if not torch.isfinite(loss): break
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimizer.step()
        
    print(f"    Final Training Loss: {loss.item():.4f}")
    
    # 5. Extract target oscillator states for each category
    print(f"\n  [Phase 3] Extracting electromagnetic signatures for visual categories...")
    states = extract_target_oscillator_states(model, x_all)
    magnitudes = torch.abs(states).numpy()
    
    target_profiles = {}
    for cat in categories:
        idx = [i for i, l in enumerate(all_labels_flat) if l == cat]
        if idx:
            target_profiles[cat] = magnitudes[idx].mean(axis=0)
            
    # 6. Apply Bayesian SGLD Estimation
    print(f"\n  [Phase 4] Inferring spatial field sources via Bayesian SGLD...")
    field_estimates = {}
    
    for cat in categories:
        print(f"\n    Estimating field cause for category: {cat.upper()}")
        tgt = target_profiles[cat]
        
        # We run SGLD to find the field 'z' that maximizes the posterior probability 
        # of producing the target D-LinOSS oscillator state signature
        estimated_field = sgld_field_estimation(
            model, tgt, num_voxels=max_voxels, iterations=300
        )
        field_estimates[cat] = estimated_field
        
        # Analyze the estimated field
        top_activations = np.argsort(np.abs(estimated_field))[-5:][::-1]
        print(f"      Top highly active voxels driving this category:")
        for v in top_activations:
            crd = selected_coords[v]
            val = estimated_field[v]
            print(f"        Voxel {v:3d} at [{crd[0]:2d},{crd[1]:2d},{crd[2]:2d}]: {val:+.3f}")

    # Output to disk
    output_dir = os.path.join(os.path.dirname(__file__), '..', 
                              'dlinoss_results', f'BayesianField_{subject_name}')
    os.makedirs(output_dir, exist_ok=True)
    
    # We can save these field estimates back out to NIfTI format for viewing in a brain viewer
    print(f"\n  [Phase 5] Saving deduced fields to NIfTI volumes...")
    ref_img = nib.load(os.path.join(subject_dir, 'func', 'sub-4_task-objectviewing_run-01_bold.nii.gz'))
    affine = ref_img.affine
    shape = ref_img.shape[:3]
    
    for cat, field in field_estimates.items():
        vol = np.zeros(shape)
        for i, (f_val, crd) in enumerate(zip(field, selected_coords)):
            vol[crd[0], crd[1], crd[2]] = f_val
            
        img = nib.Nifti1Image(vol, affine)
        nib.save(img, os.path.join(output_dir, f'estimated_field_{cat}.nii.gz'))
        
    print(f"  Saved spatial field cause maps to {output_dir}")

def main():
    base = os.path.join(os.path.dirname(__file__), '..', 'data', 'openneuro', 'ds000105')
    # Because this is an intensive Bayesian simulation, we'll test on sub-4 first
    run_bayesian_investigation(os.path.join(base, 'sub-4'), 'sub-4', max_voxels=300)

